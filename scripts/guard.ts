/**
 * Guard for the two mechanical rules in CLAUDE.md that are easy to break in
 * passing: no em dash or en dash anywhere, and the five UI message files
 * carry the same key set. It runs as the PostToolUse hook on Edit and Write
 * (`.claude/settings.json`), so a slip is reported to the session the moment
 * it lands, and it can be run by hand:
 *
 *   pnpm guard <file> [file...]        check these files
 *   pnpm guard --all                   every tracked text file (AGENTS.md is
 *                                      written by `next dev` and skipped)
 *   echo '<hook json>' | pnpm guard    as the hook calls it: reads
 *                                      tool_input.file_path from stdin
 *
 * Exit 2 with the findings on stderr (Claude Code feeds stderr of a PostToolUse
 * hook back to the model), 0 when the file is clean, missing or binary.
 * It prints paths, line numbers and key names only, never file contents.
 */
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync } from "node:fs";
import { relative, resolve, sep } from "node:path";

const ROOT = process.cwd();
const LANGS = ["ja", "en", "zh", "ko", "vi"] as const;
const MESSAGE_DIR = "lib/i18n/messages";
const MESSAGE_FILES = LANGS.map((l) => `${MESSAGE_DIR}/${l}.json`);
const DASHES: Record<string, string> = { "—": "em dash (U+2014)", "–": "en dash (U+2013)" };
const DASH_RE = /[–—]/;
/** Files `--all` leaves out: generated by tools, not written in this repository. */
const GENERATED = new Set(["AGENTS.md"]);
const BINARY_EXT = /\.(png|jpe?g|gif|webp|ico|pdf|woff2?|ttf|otf|zip|gz|mp4|mov)$/i;

function normalize(path: string): string {
  return relative(ROOT, resolve(ROOT, path)).split(sep).join("/");
}

function isText(path: string): boolean {
  if (BINARY_EXT.test(path)) return false;
  const head = readFileSync(path).subarray(0, 8000);
  return !head.includes(0);
}

/** Line numbers and kinds of every dash in the file. */
function dashFindings(path: string): string[] {
  const out: string[] = [];
  const lines = readFileSync(path, "utf8").split("\n");
  lines.forEach((line, i) => {
    if (!DASH_RE.test(line)) return;
    const kinds = Array.from(new Set(Array.from(line).filter((ch) => ch in DASHES).map((ch) => DASHES[ch])));
    out.push(`${normalize(path)}:${i + 1}: ${kinds.join(" and ")}. CLAUDE.md rule 7: use a comma, colon or full stop.`);
  });
  return out;
}

/** Missing and extra keys per message file, against the union of all five. */
function parityFindings(): string[] {
  const keys = new Map<string, Set<string>>();
  const out: string[] = [];
  for (const file of MESSAGE_FILES) {
    const abs = resolve(ROOT, file);
    if (!existsSync(abs)) {
      out.push(`${file}: missing`);
      continue;
    }
    try {
      const parsed = JSON.parse(readFileSync(abs, "utf8")) as Record<string, unknown>;
      keys.set(file, new Set(Object.keys(parsed)));
    } catch (e) {
      out.push(`${file}: not valid JSON (${e instanceof Error ? e.message : String(e)})`);
    }
  }
  if (out.length) return out;
  const union = new Set<string>();
  for (const set of keys.values()) for (const k of set) union.add(k);
  for (const [file, set] of keys) {
    const missing = [...union].filter((k) => !set.has(k));
    if (missing.length) out.push(`${file}: missing ${missing.length} key(s): ${missing.join(", ")}`);
  }
  if (out.length) out.push("CLAUDE.md rule 1: every key exists in all five message files (ja, en, zh, ko, vi).");
  return out;
}

function check(paths: string[]): string[] {
  const findings: string[] = [];
  let touchedMessages = false;
  for (const p of paths) {
    const abs = resolve(ROOT, p);
    if (!existsSync(abs) || !isText(abs)) continue;
    findings.push(...dashFindings(abs));
    if (MESSAGE_FILES.includes(normalize(abs))) touchedMessages = true;
  }
  if (touchedMessages) findings.push(...parityFindings());
  return findings;
}

/** The file the hook was called for, from the JSON Claude Code writes to stdin. */
function pathFromHookInput(): string | null {
  let raw = "";
  try {
    raw = readFileSync(0, "utf8");
  } catch {
    return null;
  }
  if (!raw.trim()) return null;
  try {
    const input = JSON.parse(raw) as { tool_input?: { file_path?: unknown } };
    const p = input.tool_input?.file_path;
    return typeof p === "string" ? p : null;
  } catch {
    return null;
  }
}

function trackedTextFiles(): string[] {
  return execFileSync("git", ["ls-files", "-z"], { cwd: ROOT, encoding: "utf8" })
    .split("\0")
    .filter((f) => f && !GENERATED.has(f) && !BINARY_EXT.test(f));
}

function main() {
  const args = process.argv.slice(2);
  let paths: string[];
  if (args.includes("--all")) {
    paths = trackedTextFiles();
  } else if (args.length) {
    paths = args;
  } else {
    const fromHook = pathFromHookInput();
    if (!fromHook) return; // not a file tool, or nothing to check
    paths = [fromHook];
  }
  const findings = check(paths);
  if (findings.length === 0) return;
  console.error(`guard: ${findings.length} finding(s)`);
  for (const f of findings) console.error(`  ${f}`);
  process.exit(2);
}

main();
